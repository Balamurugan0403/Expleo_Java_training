package Java_core;
import java.util.*;
public class Ifelseifelse {
	/*if elseif else*/
	public static void main(String[]args) {
	Scanner s=new Scanner(System.in);
	String color=s.next();
    if(color.equals("blue")) {
    	System.out.println("color is:"+color);
    }
    else if(color.equals("green")) {
    	System.out.println("color is:"+color);
    }
    else {
    	System.out.println("color is:"+color);
    }
}
}